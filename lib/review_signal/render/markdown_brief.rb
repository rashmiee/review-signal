# frozen_string_literal: true

module ReviewSignal
  module Render
    class MarkdownBrief
      MARKER = "<!-- review-signal:v1 -->"
      SEVERITY_LABELS = {
        "critical" => "CRITICAL",
        "high" => "HIGH",
        "medium" => "MEDIUM",
        "low" => "LOW"
      }.freeze

      attr_reader :context, :area_summary, :risk_flags, :test_signal

      def initialize(context:, area_summary:, risk_flags:, test_signal:)
        @context = context
        @area_summary = area_summary
        @risk_flags = risk_flags
        @test_signal = test_signal
      end

      def render
        [
          MARKER,
          "## Review Signal",
          "",
          summary_line,
          "",
          "### What changed",
          what_changed_lines,
          "",
          "### Risk flags",
          risk_flag_lines,
          "",
          "### Review focus",
          review_focus_lines,
          "",
          "### Test signal",
          test_signal_lines,
          "",
          "---",
          "<sub>Generated by Review Signal v#{ReviewSignal::VERSION}</sub>",
          ""
        ].flatten.join("\n")
      end

      private

      def summary_line
        "**Summary:** #{pluralize(context.files.count, 'file')} - #{area_summary_text} - #{risk_flag_summary}"
      end

      def area_summary_text
        return "no classified areas" if area_summary.empty?

        area_summary.map do |area, count|
          "#{area.to_s.tr('_', ' ')} (#{count})"
        end.join(", ")
      end

      def risk_flag_summary
        high_count = risk_flags.count { |flag| %w[critical high].include?(flag.severity.to_s) }
        "#{pluralize(high_count, 'high-risk flag')}"
      end

      def what_changed_lines
        return ["- No changed files found."] if area_summary.empty?

        area_summary.map do |area, count|
          "- #{area.to_s.tr('_', ' ')}: #{pluralize(count, 'file')}"
        end
      end

      def risk_flag_lines
        return ["- No path-based risk flags detected."] if risk_flags.empty?

        risk_flags.map do |flag|
          "- [#{SEVERITY_LABELS.fetch(flag.severity.to_s, flag.severity.to_s.upcase)}] #{flag.message}"
        end
      end

      def review_focus_lines
        focus = risk_flags.flat_map(&:review_focus)
        focus += test_signal.files_without_direct_spec_change.map do |path|
          "Confirm test coverage for `#{path}`."
        end
        focus = focus.uniq

        return ["- No specific review focus generated."] if focus.empty?

        focus.map { |item| "- #{item}" }
      end

      def test_signal_lines
        missing = test_signal.files_without_direct_spec_change
        return ["Direct spec changes detected for changed app files, or no app code changed."] if missing.empty?

        ["No direct spec change detected for:", missing.map { |path| "- `#{path}`" }]
      end

      def pluralize(count, singular)
        "#{count} #{count == 1 ? singular : "#{singular}s"}"
      end
    end
  end
end
