# frozen_string_literal: true

require "spec_helper"

RSpec.describe ReviewSignal::Render::MarkdownBrief do
  it "renders stable output without timestamps or checkboxes" do
    context = ReviewSignal::PullRequestContext.new(
      repo: "owner/repo",
      number: 12,
      title: "Add invoices",
      base_sha: "base",
      head_sha: "head",
      files: ["app/services/create_invoice.rb", "db/migrate/20260101000000_add_invoices.rb"]
    )
    risk_flag = ReviewSignal::Rules::RiskFlag.new(
      id: "migration",
      severity: "high",
      message: "Schema change detected.",
      review_focus: ["Confirm rollback path."],
      evidence: [ReviewSignal::Rules::Evidence.new(path: "db/migrate/20260101000000_add_invoices.rb")]
    )
    test_signal = ReviewSignal::Analyzers::TestSignal.new(context.files)

    markdown = described_class.new(
      context: context,
      area_summary: { migrations: 1, services: 1 },
      risk_flags: [risk_flag],
      test_signal: test_signal
    ).render

    expect(markdown).to include("<!-- review-signal:v1 -->")
    expect(markdown).to include("**Summary:** 2 files")
    expect(markdown).to include("- [HIGH] Schema change detected.")
    expect(markdown).to include("`db/migrate/20260101000000_add_invoices.rb`")
    expect(markdown).to include("No direct spec change detected for:")
    expect(markdown).to include("<sub>Generated by Review Signal v#{ReviewSignal::VERSION}</sub>")
    expect(markdown).not_to include("[ ]")
    expect(markdown).not_to match(/updated on/i)
  end
end

